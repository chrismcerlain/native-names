// Builds ../map-data.js from world-atlas countries-110m.json
import fs from 'node:fs';
import * as topojson from 'topojson-client';
import { geoNaturalEarth1, geoPath } from 'd3-geo';

const src = process.argv[2];
const topo = JSON.parse(fs.readFileSync(src, 'utf8'));
const fc = topojson.feature(topo, topo.objects.countries);
fc.features = fc.features.filter(f => f.id !== '010' && f.id); // drop Antarctica + unnamed

const W = 1000;
const proj = geoNaturalEarth1().fitWidth(W, { type: 'Sphere' });
const H = Math.ceil(geoPath(proj).bounds({ type: 'Sphere' })[1][1]);
const path = geoPath(proj).digits(1);

// hand overrides for countries with far-flung territory: [minLon, minLat, maxLon, maxLat]
const OVERRIDE = {
  '578': [4, 57.5, 31.5, 71.5],   // Norway (skip Svalbard)
  '250': [-5.5, 41, 10, 51.5],    // France (skip French Guiana)
  '643': [20, 41, 180, 78],       // Russia
  '242': [176.8, -19.3, 180, -16.1], // Fiji (crosses the date line)
};

function polyBounds(coords) {
  const b = path.bounds({ type: 'Polygon', coordinates: coords });
  return b;
}
function dist(a, b) {
  const dx = Math.max(0, Math.max(a[0][0], b[0][0]) - Math.min(a[1][0], b[1][0]));
  const dy = Math.max(0, Math.max(a[0][1], b[0][1]) - Math.min(a[1][1], b[1][1]));
  return Math.hypot(dx, dy);
}

const countries = {};
const borders = path(topojson.mesh(topo, topo.objects.countries, (a, b) => a !== b));
for (const f of fc.features) {
  const d = path(f);
  if (!d) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const parts = polys.map(c => ({ c, b: polyBounds(c), a: path.area({ type: 'Polygon', coordinates: c }) }));
  parts.sort((x, y) => y.a - x.a);
  let main = parts[0].b.map(p => p.slice());
  let box = parts[0].b.map(p => p.slice());
  for (const p of parts.slice(1)) {
    const dd = dist(main, p.b);
    if (dd <= 30 || (dd <= 90 && p.a >= 0.1 * parts[0].a)) {
      box[0][0] = Math.min(box[0][0], p.b[0][0]); box[0][1] = Math.min(box[0][1], p.b[0][1]);
      box[1][0] = Math.max(box[1][0], p.b[1][0]); box[1][1] = Math.max(box[1][1], p.b[1][1]);
    }
  }
  if (OVERRIDE[f.id]) {
    const [x0, y0, x1, y1] = OVERRIDE[f.id];
    const pts = [[x0, y0], [x1, y0], [x1, y1], [x0, y1], [(x0 + x1) / 2, y1], [(x0 + x1) / 2, y0]].map(p => proj(p));
    box = [[Math.min(...pts.map(p => p[0])), Math.min(...pts.map(p => p[1]))], [Math.max(...pts.map(p => p[0])), Math.max(...pts.map(p => p[1]))]];
  }
  const centroid = path.centroid({ type: 'Polygon', coordinates: parts[0].c }).map(v => +v.toFixed(1));
  countries[f.id] = {
    n: f.properties.name,
    d,
    b: [box[0][0], box[0][1], box[1][0] - box[0][0], box[1][1] - box[0][1]].map(v => +v.toFixed(1)),
    c: centroid,
  };
}

const out = `// Generated by tools/build-map.mjs from world-atlas@2.0.2 countries-110m (Natural Earth, public domain)
const MAP = ${JSON.stringify({ w: W, h: H, sphere: path({ type: 'Sphere' }), borders, countries })};
`;
fs.writeFileSync(new URL('../map-data.js', import.meta.url), out);
console.log('countries:', Object.keys(countries).length, 'size:', (out.length / 1024).toFixed(0), 'KB', 'H', H);
